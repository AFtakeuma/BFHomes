#!/usr/bin/env node
/**
 * Replace readdy.ai / static.readdy.ai image URLs with local real photo paths.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const manifest = JSON.parse(
  readFileSync(path.join(ROOT, "app", "data", "real-photos-manifest.json"), "utf8")
);

const p = (id, kind) => manifest.projects[String(id)][kind];

const seqToPath = {
  "1": p(1, "before"),
  "2": p(1, "after"),
  "3": p(2, "before"),
  "4": p(2, "after"),
  "5": p(3, "before"),
  "6": p(3, "after"),
  "8": p(4, "before"),
  "9": p(4, "after"),
  "10": p(5, "before"),
  "11": p(5, "after"),
  "12": p(6, "before"),
  "13": p(6, "after"),
  "14": p(7, "before"),
  "15": p(7, "after"),
  "16": p(8, "before"),
  "17": p(8, "after"),
  "18": p(9, "before"),
  "19": p(9, "after"),
  "20": p(10, "before"),
  "21": p(10, "after"),
  "22": p(11, "before"),
  "23": p(11, "after"),
  "24": p(12, "before"),
  "25": p(12, "after"),
  "27": p(2, "after"),
  "28": p(3, "after"),
  "29": p(6, "after"),
};

const staticReplacements = [
  [
    "https://static.readdy.ai/image/482db82fa6135662cb175aa58592a390/9747dda6203049373e2ef3554fb2c9fb.jfif",
    p(2, "before"),
  ],
  [
    "https://static.readdy.ai/image/482db82fa6135662cb175aa58592a390/58414e870e011c5caece62221230918d.jfif",
    p(2, "after"),
  ],
];

const heroReplacements = [
  [/seq=7&orientation=landscape[^'"]*/, manifest.extras["hero-living"].replace(/^\//, "") + "'"],
  [/seq=17&orientation=landscape[^'"]*/, manifest.extras["hero-living"].replace(/^\//, "") + "'"],
  [/seq=26&orientation=landscape[^'"]*/, manifest.extras["hero-living"].replace(/^\//, "") + "'"],
  [/seq=pricing-hero[^'"]*/, manifest.extras["hero-kitchen"].replace(/^\//, "") + "'"],
  [/seq=contact1[^'"]*/, manifest.extras["hero-living"].replace(/^\//, "") + "'"],
  [/seq=about1[^'"]*/, manifest.extras["hero-living"].replace(/^\//, "") + "'"],
];

const aboutSeq = {
  about2: { before: p(1, "before"), after: p(1, "after") },
  about3: p(2, "after"),
  about4: p(7, "after"),
  about5: p(2, "before"),
  avatar1: manifest.extras["about-team"],
  avatar2: manifest.extras["about-team"],
  avatar3: manifest.extras["about-team"],
};

const howSeq = {
  "14": p(1, "after"),
  "15": p(2, "before"),
  "16": p(5, "after"),
  "18": p(3, "after"),
};

function walk(dir, files = []) {
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) {
      if (name === "node_modules" || name === ".git") continue;
      walk(full, files);
    } else if (/\.(tsx?|jsx?|json)$/.test(name)) {
      files.push(full);
    }
  }
  return files;
}

function transform(content, filePath) {
  let out = content;
  let changed = false;

  for (const [from, to] of staticReplacements) {
    if (out.includes(from)) {
      out = out.split(from).join(to);
      changed = true;
    }
  }

  out = out.replace(
    /https:\/\/readdy\.ai\/api\/search-image\?[^'")\s]+/g,
    (url) => {
      const seqM = url.match(/seq=([^&]+)/);
      if (seqM && seqToPath[seqM[1]]) {
        changed = true;
        return seqToPath[seqM[1]];
      }
      const aboutM = seqM && aboutSeq[seqM[1]];
      if (typeof aboutM === "string") {
        changed = true;
        return aboutM;
      }
      if (aboutM && typeof aboutM === "object") {
        changed = true;
        return aboutM.after;
      }
      if (seqM && howSeq[seqM[1]]) {
        changed = true;
        return howSeq[seqM[1]];
      }
      changed = true;
      return manifest.extras["hero-living"];
    }
  );

  if (filePath.endsWith("layout.tsx")) {
    const fav = manifest.extras.favicon;
    out = out.replace(
      /https:\/\/readdy\.ai\/api\/search-image\?[^"]+/g,
      fav
    );
    out = out.replace(/title: "Readdy Site"/, 'title: "Before-After Homes"');
    out = out.replace(
      /description: "Generated by Readdy"/,
      'description: "賃貸住宅の原状回復・修繕の施工事例（ビフォーアフター）"'
    );
    changed = true;
  }

  return { out, changed };
}

const appDir = path.join(ROOT, "app");
const files = walk(appDir);
let touched = 0;
for (const file of files) {
  const raw = readFileSync(file, "utf8");
  const { out, changed } = transform(raw, file);
  if (changed && out !== raw) {
    writeFileSync(file, out);
    touched += 1;
  }
}

console.log(JSON.stringify({ filesUpdated: touched }));
